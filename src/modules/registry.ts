const playableMap = new Map<string, ModuleSpec>();
for (const raw of [...act1Specs, ...act2Specs, ...act3Specs, ...act4Specs, ...act5Specs, ...act6Specs]) {
  const s = fillPhases(raw);
  playableMap.set(`a${s.act}-m${s.index}`, s);
}

export const MODULES_50: ModuleSpec[] = roster.map(([act, index, title, summary]) => {
  const key = `a${act}-m${index}`;
  const playable = playableMap.get(key);
  return (
    playable ?? {
      id: key,
      act,
      index,
      title,
      summary,
      playable: false,
    }
  );
});

export function modulesOfAct(act: number): ModuleSpec[] {
  return MODULES_50.filter((m) => m.act === act);
}

export const PLAYABLE_IDS = [...playableMap.keys()];
